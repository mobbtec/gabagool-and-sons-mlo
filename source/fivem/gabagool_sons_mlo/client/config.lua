-- MLO-local (s, t, z) -> world
function GS.toWorld(x, y, z)
    local r = math.rad(GS.YAW)
    local c, s = math.cos(r), math.sin(r)
    return vector3(GS.ORIGIN.x + x * c - y * s, GS.ORIGIN.y + x * s + y * c, GS.ORIGIN.z + (z or 0.0))
end

-- heading (GTA degrees) of a direction given in MLO-local coordinates
function GS.heading(dx, dy)
    local r = math.rad(GS.YAW)
    local c, s = math.cos(r), math.sin(r)
    local wx, wy = dx * c - dy * s, dx * s + dy * c
    return (math.deg(math.atan(-wx, wy)) + 360.0) % 360.0
end

