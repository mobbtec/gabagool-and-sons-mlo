# LONG PIG 0.3.1-j: client/interact_data.lua - places where a player can sit or work (revision).
# Pure Python. Seats come from the kit (dining chairs, booth benches, counter / ledge stools, back-room chairs);
# work spots are fixed next to the equipment. Points closer than 1.4 m to a restaurant.lua control are dropped
# (both scripts use E). Local metres; heading = MLO-local degrees (client adds GS.YAW).
import sys, math, json
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gs_v030_kit as K
import gs_v029_kit as K9
import gs_v021_kit as V
import gs_v027_kit as K7

SEAT_Z = 0.50
P = []


def add(kind, s, t, z, h, scen, label):
    P.append(dict(kind=kind, s=round(s, 3), t=round(t, 3), z=round(z, 3), h=round(h % 360.0, 1), sc=scen, label=label))


for n, s, t, zb, yaw in K9.chairs_open():                        # dining chairs (entity set lp_open)
    if hasattr(K, "_mkt_in_banq") and (K._mkt_in_banq(s, t, 0.0) or K._mkt_near_ctable(s, t)):
        continue                                                 # 0.3.2: banquette / centre tables removed (mini market)
    add("chair", s, t, zb + SEAT_Z, yaw + 180.0, "PROP_HUMAN_SEAT_CHAIR_FOOD", "Сесть за стол")
for a in V.booth_bays():                                         # booth benches: 2 places on each bench
    for tt in (-0.88, -0.36):
        add("booth", a + 0.33, tt, SEAT_Z - 0.03, -90.0, "PROP_HUMAN_SEAT_CHAIR_FOOD", "Сесть в бокс")
        add("booth", a + V.BOOTH_PITCH - 0.33, tt, SEAT_Z - 0.03, 90.0, "PROP_HUMAN_SEAT_CHAIR_FOOD", "Сесть в бокс")
for n, s, t, zb, yaw in K.vanilla_props():
    if n == "lr_prop_clubstool_01":                              # counter stools, face the counter (+s)
        add("stool", s, t, zb + 0.62, -90.0, "PROP_HUMAN_SEAT_BAR", "Сесть у стойки")
    elif n == "prop_bar_stool_01":                               # window ledge stools, face the ledge (-s)
        add("stool", s, t, zb + 0.62, 90.0, "PROP_HUMAN_SEAT_BAR", "Сесть у окна")
    elif n in ("v_res_fa_chair01", "v_ret_gc_chair02") and t > 8.4:   # back room table
        add("chair", s, t, zb + SEAT_Z, yaw + 180.0, "PROP_HUMAN_SEAT_CHAIR_DRINK", "Сесть (перерыв)")
# work spots
add("work", 15.00, 1.02, 0.0, -90.0, "PROP_HUMAN_BBQ", "Жарить на гриле")
add("work", 14.95, 2.60, 0.0, -90.0, "PROP_HUMAN_BBQ", "Готовить на плите")
add("work", 12.10, 3.95, 0.0, 0.0, "WORLD_HUMAN_MAID_CLEAN", "Мыть посуду")
add("work", 11.60, -0.52, 0.0, 180.0, "WORLD_HUMAN_MAID_CLEAN", "Помыть руки")
add("work", 12.95, -0.12, 0.0, 180.0, "PROP_HUMAN_BBQ", "Нарезать продукты")
add("work", 9.15, 5.95, 0.0, -90.0, "WORLD_HUMAN_AA_COFFEE", "Налить кофе")
add("work", 4.65, 10.05, 0.0, -90.0, "WORLD_HUMAN_AA_COFFEE", "Налить кофе")
add("work", 10.95, 9.05, 0.0, 90.0, "WORLD_HUMAN_CLIPBOARD", "Пересчитать товар")
add("work", 2.55, 4.70, 0.0, 0.0, "WORLD_HUMAN_JANITOR", "Помыть пол")

CTRL = [(6.86, 6.94), (6.55, 8.48), (7.34, 0.02), (7.66, 4.90), (16.14, 0.12), (10.0, -0.5), (6.45, 9.98)]
keep = [p for p in P if min(math.hypot(p["s"] - c[0], p["t"] - c[1]) for c in CTRL) >= 1.4]
dropped = [p for p in P if p not in keep]
ROOT = HERE.parents[1]
L = ["-- GENERATED by source/scripts/gs_50_interact_data.py - do not edit. Sit / work places (MLO-local metres, heading",
     "-- relative to the MLO). kind = chair (dining chairs of the lp_open set) | booth | stool | work.",
     "GS_INTERACT = {"]
for p in keep:
    L.append("    { kind = '%s', s = %.3f, t = %.3f, z = %.3f, h = %.1f, sc = '%s', label = '%s' }," %
             (p["kind"], p["s"], p["t"], p["z"], p["h"], p["sc"], p["label"]))
L.append("}")
(ROOT / "source" / "fivem" / "gabagool_sons_mlo" / "client" / "interact_data.lua").write_text("\n".join(L) + "\n", encoding="utf-8")
print("points", len(keep), "dropped", [(d["label"], d["s"], d["t"]) for d in dropped])
