# LONG PIG 0.3.1-c: client/blinds_data.lua for the animated blinds (pure Python, no Blender). Takes the slats of the four
# 'open' panes from gs_v026_kit exactly as the hall drawable used to have them: pivot (top centre, MLO-local metres), open
# heading and closed heading (degrees relative to the MLO, the client adds GS.YAW).
import sys, math, json
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gs_v026_kit as K6
orig_slat = getattr(K6, "_slat_static", K6._slat)
orig_pane = getattr(K6, "_blind_pane_static", K6.blind_pane)
REC, CUR = [], {"pane": -1, "anim": False}
CLOSED_DEG = 7.0


def slat(out, fr, u, d0, z0, z1, ang, ci, tilt=0.0):
    if CUR["anim"]:
        p = fr.p(u, d0, z1)
        do = fr.v(math.cos(ang), math.sin(ang), 0.0)
        c = math.radians(CLOSED_DEG)
        dc = fr.v(math.cos(c), math.sin(c), 0.0)
        REC.append(dict(pane=CUR["pane"], s=round(p[0], 4), t=round(p[1], 4), z=round(p[2], 4), len=round(z1 - z0, 3),
                        ho=round(math.degrees(math.atan2(do[1], do[0])), 2), hc=round(math.degrees(math.atan2(dc[1], dc[0])), 2)))
    return orig_slat(out, fr, u, d0, z0, z1, ang, ci, tilt)


def pane(fr, a, b, d0, pattern, seed):
    CUR["pane"] += 1
    CUR["anim"] = pattern[0] == "open"
    try:
        return orig_pane(fr, a, b, d0, pattern, seed)
    finally:
        CUR["anim"] = False


K6._slat, K6.blind_pane = slat, pane
K6.blinds_faces()
ROOT = HERE.parents[1]
L = ["-- GENERATED by source/scripts/gs_49_blinds_data.py - do not edit. Slats of the animated vertical blinds.",
     "-- s, t, z = pivot (top centre) in MLO-local metres; ho / hc = open / closed heading in degrees relative to the MLO.",
     "GS_BLINDS = {"]
for r in REC:
    L.append("    { pane = %d, s = %.4f, t = %.4f, z = %.4f, ho = %.2f, hc = %.2f }," % (r["pane"], r["s"], r["t"], r["z"], r["ho"], r["hc"]))
L.append("}")
(ROOT / "source" / "fivem" / "gabagool_sons_mlo" / "client" / "blinds_data.lua").write_text("\n".join(L) + "\n", encoding="utf-8")
(ROOT / "docs" / "_raw" / "blinds_data_v031.json").write_text(json.dumps(REC), encoding="utf-8")
print("slats", len(REC), "panes", sorted(set(r["pane"] for r in REC)), "len", sorted(set(r["len"] for r in REC))[:3], sorted(set(r["len"] for r in REC))[-1])
