# LONG PIG — v0.2.6: generate the asset audit (KEEP / REFINE / REPLACE / REMOVE), the per-fixture light schedule and the
# material source register straight from the kits, so the documents match what is actually built. Pure Python.
#   python gs_36_v026_docs.py [<project_root>]   -> docs/v026/LONG_PIG_V026_{ASSET_AUDIT,LIGHTING_SCHEDULE,MATERIAL_SOURCES}.md
import sys, json, collections
from pathlib import Path

ROOT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "source" / "scripts"))
import gs_v025_kit as K5   # noqa: E402
import gs_v026_kit as K    # noqa: E402

OUT = ROOT / "docs" / "v026"
OUT.mkdir(parents=True, exist_ok=True)
tri = lambda fs: sum(len(f["v"]) - 2 for f in fs if f)

# ------------------------------------------------------------------ asset audit
old = collections.Counter(n for n, *_ in K5.vanilla_props())
new = collections.Counter(n for n, *_ in K.vanilla_props())
rows = []
REASON_KEEP = "kept: verified v0.2.5 placement, fits the deli"
for name in sorted(set(old) | set(new)):
    o, n = old.get(name, 0), new.get(name, 0)
    if n == 0:
        why = K.REMOVED.get(name) or next((v for k, v in K.REMOVED.items() if k.endswith("*") and name.startswith(k[:-1])), "")
        rows.append((name, o, n, "REMOVE", why))
    elif o == 0:
        src = "docs/_raw/vanilla_scan_v026.json" if name in K.VB_V026 else "docs/_raw/vanilla_catalogue_v021.json"
        rows.append((name, o, n, "ADD", f"v0.2.6 service / history detail (verified name + bounds: {src})"))
    elif n < o:
        rows.append((name, o, n, "REFINE", "duplicate placement removed" if name == "v_ret_gc_clock" else "fewer placements"))
    elif name == "v_ilev_fib_sprklr":
        rows.append((name, o, n, "REFINE", "one sprinkler moved out of the new queue troffer"))
    else:
        rows.append((name, o, n, "KEEP", REASON_KEEP))
GEOM = [
    ("Shell: walls, red tile wainscot, cream brick, ceiling plane", "KEEP / REFINE", "same geometry, portals, collision; floor A re-aged on a 4 m repeat, ceiling tile without baked repeat"),
    ("Doors D1 / D2 / D3, windows W1 / W2, vanilla overrides, occluders", "LOCK", "untouched (no file of stream/vanilla_override changed)"),
    ("T-bar grid, counter soffit, menu boards", "KEEP", "unchanged"),
    ("2x4 troffers (10)", "REFINE", "recessed lens + sloped reflector + latches, 4 lamp variants, each with its own engine light"),
    ("Troffers (5 new): booth row + queue", "REPLACE", "replace 5 hanging enamel dome pendants"),
    ("Opal globe pendants over the centre tables (2)", "REMOVE", "brief 4.1 (dangling lamps); fans over those tables instead"),
    ("Supply diffusers (2), return grille (1), replaced tiles (3), stains, wall-top grime", "ADD", "brief 4.2"),
    ("Booths (3) + banquettes (2)", "REFINE", "same layout and ergonomics; sitting dips, softened front roll, flatter worn channels, welt seam, per-bench UV, edge wear"),
    ("Centre tables (2) + mismatched chairs", "KEEP", "unchanged (pendants above removed)"),
    ("Small tricolore on P2", "REMOVE", "owner rejected the current flag (brief 1.2 / 8)"),
    ("P2 big wall", "REFINE", "zones A-D: supplier poster, photos, plaque, cork board, catering notice, ghosts / anchors / patches / chips / scuffs"),
    ("Cashier back wall P1 (v0.2.5 hero)", "KEEP", "unchanged; till area + staff mat + deli-prep details added"),
    ("W1 / W2 vertical blinds", "ADD", "original PVC slats in the reveals, partly open, one pane stacked"),
    ("Entry mat", "KEEP", "plus street grit around it, store-hours card + sticker residue on the chamfer pier"),
    ("Cleaning corner", "ADD", "back room by the P1 door: mop bucket, wet-floor sign, broom, spray"),
    ("Ceiling fans (2)", "ADD", "vanilla prop_outdoor_fan_01, client-side, slow rotation (client/fans.lua)"),
    ("Gumball machines outside", "REFINE", "regrouped on the blank NW facade, ray-cast flush to the wall (client/exterior.lua)"),
]
L = ["# LONG PIG v0.2.6 — asset audit (KEEP / REFINE / REPLACE / REMOVE / ADD)", "",
     "Generated by `source/scripts/gs_36_v026_docs.py` from `gs_v025_kit` (baseline) and `gs_v026_kit` (this build). Default is KEEP.", "",
     "## Geometry groups (our own drawable `gs_v021_hall`, shell `gs_proto_shell`)", "",
     "| Group | Decision | Reason |", "|---|---|---|"]
L += [f"| {a} | **{b}** | {c} |" for a, b, c in GEOM]
L += ["", f"Hall triangles: v0.2.5 {tri(K5.hall_faces()):,} -> v0.2.6 {tri(K.hall_faces()):,}.", "",
      "## Vanilla GTA V props (archetype names only, nothing shipped)", "",
      f"Placements: v0.2.5 {sum(old.values())} -> v0.2.6 {sum(new.values())}; archetypes {len(old)} -> {len(new)}.", "",
      "| Archetype | v0.2.5 | v0.2.6 | Decision | Reason |", "|---|---|---|---|---|"]
L += [f"| `{a}` | {o} | {n} | **{d}** | {w} |" for a, o, n, d, w in rows]
L += ["", "Client-side (not in the map): `prop_outdoor_fan_01` x2 (fans), `prop_gumball_01`, `prop_gumball_02` (outside).", ""]
(OUT / "LONG_PIG_V026_ASSET_AUDIT.md").write_text("\n".join(L), encoding="utf-8")

# ------------------------------------------------------------------ light schedule
geo = {(i, j): (i, j, ns, nt, lamp) for (i, j, ns, nt, lamp) in K.TROFFERS}
LAMP_NAME = {0: "cool white", 1: "aged warm tube", 2: "weak (one tube out)", 3: "dirty lens"}
L = ["# LONG PIG v0.2.6 — light schedule (fixture geometry <-> engine light)", "",
     "Generated from `gs_v026_kit.lights()`. Coordinates are MLO-local metres (s, t, z above the shop floor). Intensities are",
     "starting values chosen in Blender / from earlier builds — **not yet calibrated in FiveM** (brief 4.4: the engine and",
     "timecycle `lp_longpig_hall` decide the final look). Time flags: 24 h unless noted.", "",
     "| # | Fixture | Geometry | Emitter | Engine light | Colour (RGB) | I | Falloff m | Cone out/in | Flags | Hours |",
     "|---|---|---|---|---|---|---|---|---|---|---|"]
for k, l in enumerate(K.lights(), 1):
    kind = l["kind"]
    if kind.startswith("troffer"):
        sc, tc = l["pos"][0], l["pos"][1]
        cell = next(c for c in geo.values() if abs((c[0] + c[2] / 2) * K.P - sc) < 1e-3 and abs((c[1] + c[3] / 2) * K.P - tc) < 1e-3)
        g = f"troffer {cell[2]}x{cell[3]} tiles at cell ({cell[0]},{cell[1]}), recessed lens"
        em = f"lp5_troffer variant {cell[4]} ({LAMP_NAME[cell[4]]})"
    elif kind == "window_day_fill":
        g, em = "behind the W1 / W2 glass, above the blinds", "daylight (no emitter)"
    elif kind in ("banquette_key", "ledge_can", "entrance_can", "soffit_can"):
        g, em = "recessed can (brass trim, opal lens)", "lp_glow lens"
    elif kind == "case":
        g, em = "deli case canopy strip", "case glass"
    elif kind == "menu_glow":
        g, em = "backlit menu cabinet", "lp4_menu emissive"
    elif kind == "entrance_wall_light":
        g, em = "v_med_cor_walllight (opal wall fixture, pier B)", "vanilla fixture"
    else:
        g, em = "staff aisle (hidden behind the soffit)", "—"
    hours = "07-19" if l.get("time", 0xFFFFFF) != 0xFFFFFF else "24 h"
    c = "(%.2f, %.2f, %.2f)" % tuple(l["color"])
    cone = f"{l['cone_out']:.0f}/{l['cone_in']:.0f}" if l["type"] == "SPOT" else "—"
    p = "(%.2f, %.2f, %.2f)" % l["pos"]
    L.append(f"| {k} | {kind} {p} | {g} | {em} | {l['type']} | {c} | {l['intensity']} | {l['falloff']} | {cone} | "
             f"{', '.join(l['flags']) or '—'} | {hours} |")
cnt = collections.Counter(l["kind"].split("_lamp")[0] for l in K.lights())
L += ["", f"Total {len(K.lights())} hall lights (v0.2.5: {len(K5.lights())}). Shadow casters: "
      f"{sum(1 for l in K.lights() if 'static_shadows' in l['flags'])} (5 troffers over booths / queue + 4 banquette cans).",
      "Removed: 3 booth pendant keys + 3 bulb coronas, 2 queue pendant keys + 2 coronas, 2 centre globe keys + 2 coronas.",
      "", "Fans and blinds do not cast engine shadows; nothing here claims physically correct sun shadows (brief 5.3).", ""]
(OUT / "LONG_PIG_V026_LIGHTING_SCHEDULE.md").write_text("\n".join(L), encoding="utf-8")

# ------------------------------------------------------------------ material sources
rep = json.loads((ROOT / "source" / "textures" / "v026" / "lp5_textures_report.json").read_text(encoding="utf-8"))
L = ["# LONG PIG v0.2.6 — material sources (legal register)", "",
     "Every new map is **original procedural / typographic work** or a **derivative of our own earlier textures** (whose CC0 / original",
     "provenance is in `assets/registry.json`). Nothing from the reference MLO, no Rockstar pixels, no screenshots used as textures.",
     "The three snapshots in `lp5_wall` are Blender renders of OUR OWN interior with every vanilla model and the vanilla building",
     "switched off (`gs_21` with `GS_NO_VANILLA=1`). ambientCG / Poly Haven were not needed for this pass: the existing CC0-derived",
     "maps were aged further instead of being replaced (brief: preserve first).", "",
     "| Texture | Size | Format | Origin | Derived from | SHA-256 (first 16) | Operations |", "|---|---|---|---|---|---|---|"]
for t in rep["textures"]:
    L.append(f"| {t['name']} | {t['size'][0]}x{t['size'][1]} | {t['format']} | {t['origin']} | {', '.join(t['derived_from']) or '—'} | "
             f"`{t['sha256'][:16]}` | {t['operations']} |")
L += ["", "Applied mapping: floor A = shell floor (4 m per texture, `PG.FLOOR_UV_M`), ceiling = shell ceiling (5.15 m),",
      "`lp5_troffer` = troffer lenses (one variant per fixture), `lp5_blind` = slats (one column per slat), `lp5_decal` = 16-cell",
      "decal atlas, `lp5_wall` = posters / photos / notices, floor B = runtime comparison only (`/gs_floor b`).", ""]
(OUT / "LONG_PIG_V026_MATERIAL_SOURCES.md").write_text("\n".join(L), encoding="utf-8")
print("DOCS_V026", [p.name for p in OUT.glob("*.md")])
