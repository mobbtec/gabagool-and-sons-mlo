# LONG PIG v0.2.9 — write the kit data the Lua scripts need (single source of truth = the kit):
#   shared/restaurant_data.lua   LPR_DATA: interaction points, hood lamps, ticket rail, hidden compartment (MLO-local metres)
#   client/config.lua            GS.DOORS block regenerated from gs_proto_geometry (D1-D3) + gs_v029_kit.all_doors()
#   python gs_45_write_rest_data.py [<project_root>]
import sys, re, importlib
from pathlib import Path

ROOT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "source" / "scripts"))
import gs_proto_geometry as PG
K = importlib.import_module("gs_v029_kit")
RES = ROOT / "source" / "fivem" / "gabagool_sons_mlo"


def v3(p):
    return "vector3(%.4f, %.4f, %.4f)" % tuple(p)


d = K.interaction_data()
L = ["-- LONG PIG v0.2.9 — GENERATED by source/scripts/gs_45_write_rest_data.py from gs_v029_kit.interaction_data().",
     "-- MLO-local metres (s along the SW facade, t inwards, z above the MLO origin). Do not edit by hand.",
     "LPR_DATA = {"]
for k in ("switch_hall", "switch_office", "bell", "printer", "printer_paper", "hood_switch", "pickup_bell", "secret_point", "secret_hinge"):
    L.append(f"    {k} = {v3(d[k])},")
L.append("    hood_lamps = { " + ", ".join(v3(p) for p in d["hood_lamps"]) + " },")
s0, s1, t, z = d["ticket_rail"]
L.append(f"    ticket_rail = {{ s0 = {s0:.4f}, s1 = {s1:.4f}, t = {t:.4f}, z = {z:.4f} }},")
L.append(f"    secret_width = {d['secret_width']:.3f},")
L.append("    room = 'gs_front',")
L.append("    sets = { open = 'lp_open', closed = 'lp_closed' },")
L.append("}")
(RES / "shared").mkdir(parents=True, exist_ok=True)
(RES / "shared" / "restaurant_data.lua").write_text("\n".join(L) + "\n", encoding="utf-8")

# ---- GS.DOORS
names = {"gs_kitchen": "hall <-> kitchen, wood fire door with vision panel", "gs_staff_p2": "hall <-> staff corridor (EMPLOYEES ONLY)",
         "gs_boh_storage": "corridor <-> storage", "gs_boh_staff": "corridor <-> staff room", "gs_boh_office": "office, solid wood",
         "gs_boh_wc": "staff WC, private", "gs_boh_pass": "kitchen <-> storage, steel (1.9.1)", "gs_boh_cooler": "kitchen <-> walk-in cooler, steel"}
rows = ["GS.DOORS = {"]
for did, arch, pos, yaw, pk in PG.vanilla_door_entities():
    rows.append(f"    {{ id = '{did}', model = `{arch}`, pos = {v3(pos)} }},")
rows.append("    -- 0.2.9 interior doors (gs_v029_kit.all_doors(), generated by gs_45_write_rest_data.py)")
for did, arch, pos, yaw in K.all_doors():
    rows.append(f"    {{ id = '{did}', model = `{arch}`, pos = {v3(pos)} }},   -- {names.get(did, '')}")
rows.append("}")
cfg = RES / "client" / "config.lua"
txt = cfg.read_text(encoding="utf-8")
new, n = re.subn(r"GS\.DOORS = \{.*?\n\}\n", "\n".join(rows) + "\n", txt, count=1, flags=re.S)
assert n == 1, "GS.DOORS block not found"
cfg.write_text(new, encoding="utf-8")
print("WROTE restaurant_data.lua + GS.DOORS", len(K.all_doors()) + len(PG.vanilla_door_entities()), "doors")
