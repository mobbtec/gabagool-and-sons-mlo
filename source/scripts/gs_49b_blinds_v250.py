# LONG PIG 2.5.0: client/blinds_data.lua rebuilt as ONE uniform set (pure Python). 2.3.0 had slats only in 4 of the 5 window
# bays (the old static "stacked" pane was dropped with the 1.9.3 hall), two slats missing and open angles from 10 to 80 deg.
# Now: every bay of W1 (3) and W2 (2) gets slats at an 80 mm pitch, centred in the bay, one open angle (+-1.5 deg).
import random, json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
PITCH, MARGIN, Z, OPEN = 0.080, 0.050, 2.515, 58.0
W1_BAYS = ((1.332, 2.637), (2.790, 4.131), (4.270, 5.575))          # between the vanilla mullions (gs_proto_geometry.W1)
W2_BAYS = ((3.534, 4.840), (4.979, 6.319))
rnd = random.Random(250)
rows = []
def bay(pane, a, b, fixed, along_s, hc, reverse):
    n = int((b - a - 2 * MARGIN) / PITCH) + 1
    x0 = (a + b) / 2 - PITCH * (n - 1) / 2
    xs = [x0 + PITCH * k for k in range(n)]
    for x in (xs[::-1] if reverse else xs):
        s, t = (x, fixed) if along_s else (fixed, x)
        rows.append(dict(pane=pane, s=round(s, 4), t=round(t, 4), z=Z, ho=round(hc - OPEN + rnd.uniform(-1.5, 1.5), 2), hc=hc))
for i, (a, b) in enumerate(W1_BAYS):
    bay(i, a, b, -1.315, True, 173.0, True)
for i, (a, b) in enumerate(W2_BAYS):
    bay(3 + i, a, b, -2.972, False, 83.0, False)
L = ["-- GENERATED by source/scripts/gs_49b_blinds_v250.py - do not edit. Slats of the animated vertical blinds (uniform set).",
     "-- s, t, z = pivot (top centre) in MLO-local metres; ho / hc = open / closed heading in degrees relative to the MLO.",
     "GS_BLINDS = {"]
for r in rows:
    L.append("    { pane = %d, s = %.4f, t = %.4f, z = %.4f, ho = %.2f, hc = %.2f }," % (r["pane"], r["s"], r["t"], r["z"], r["ho"], r["hc"]))
L.append("}")
(ROOT / "source" / "fivem" / "gabagool_sons_mlo" / "client" / "blinds_data.lua").write_text("\n".join(L) + "\n", encoding="utf-8")
(ROOT / "docs" / "_raw" / "blinds_data_v250.json").write_text(json.dumps(rows), encoding="utf-8")
import collections
print("slats", len(rows), dict(collections.Counter(r["pane"] for r in rows)))
